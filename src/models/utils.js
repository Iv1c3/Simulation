// Набор утилитарных функций для симуляции

// Генерирует случайный цвет в формате HSL.
// Оттенок (hue) выбирается случайным образом от 0 до 359 градусов.
// Насыщенность и яркость фиксированы для создания приятных цветов.
export function randomColor() {
  const h = Math.floor(Math.random() * 360);           // случайный угол (0–359)
  return `hsl(${h},70%,60%)`;                          // строка формата HSL
}

// Случайный пол: возвращает 'male' или 'female' с равной вероятностью.
export function randomGender() {
  return Math.random() < 0.5 ? 'male' : 'female';      // 50% шанс каждого пола
}

// Возвращает случайное число от a (включительно) до b (не включительно).
// Используется для генерации координат, размера, скорости и других параметров.
export function randomBetween(a, b) {
  return a + Math.random() * (b - a);                  // равномерное распределение в диапазоне [a, b)
}
